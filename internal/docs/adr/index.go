package adr

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/EqualSoftware/claude-dx/internal/docs/docfile"
)

const indexHeader = `<!-- Generated by claude-dx. Do not edit. -->
# Decisions

This folder has the architecture decision records (ADRs) of the project. Use ` + "`/dx:adr`" + ` to record a decision.

| ADR | Title | Status | Date |
| :--- | :--- | :--- | :--- |
`

// WriteIndex makes docs/decisions/README.md from the header of the ADR files.
// It is for persons on GitHub; the model uses adr_list.
func (s Store) WriteIndex() error {
	list, _, err := s.List()
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString(indexHeader)
	for _, e := range list {
		fmt.Fprintf(&b, "| [%s](%s) | %s | %s | %s |\n", kind.ID(e.Number), e.File, e.Title, e.Status, e.Date)
	}
	return docfile.Write(filepath.Join(s.Dir, "README.md"), []byte(b.String()))
}
