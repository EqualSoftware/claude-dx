package task

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const indexHeader = `<!-- Generated by claude-dx. Do not edit. -->
# Tasks

This file lists all tasks. Each task is a spec file in this folder: ` + "`TASK-NNN-<short-kebab-title>.md`" + `. Use ` + "`/dx:task`" + ` to make or update a task.

Do not edit this file. The claude-dx task tools make it again from the YAML frontmatter of the task files after each change.

## Priority

| Priority | Meaning |
| :--- | :--- |
| ` + "`P0`" + ` | Blocks other work or breaks the build. Do it first. |
| ` + "`P1`" + ` | Required for the current goal. |
| ` + "`P2`" + ` | Useful. Do it when P0 and P1 tasks are done. |
| ` + "`P3`" + ` | Idea. Do it only if time permits. |

## Status

` + "`Draft` → `In Review` → `Approved` → `In Development` → `Done`" + `. A task can also be ` + "`Blocked` or `Cancelled`" + `.

## Open tasks

Sort by priority, then by ID.

| ID | Title | Status | Priority | Area | Depends on |
| :--- | :--- | :--- | :--- | :--- | :--- |
`

const closedHeader = `
## Closed tasks

` + "`Done` and `Cancelled`" + ` tasks.

| ID | Title | Status | Closed |
| :--- | :--- | :--- | :--- |
`

// WriteIndex makes docs/tasks/INDEX.md from the frontmatter of the task files.
// It is for persons on GitHub; the model uses task_list.
func (s Store) WriteIndex() error {
	tasks, _, err := s.List(Filter{Status: "all"})
	if err != nil {
		return err
	}
	open, closed := split(tasks)
	var b strings.Builder
	b.WriteString(indexHeader)
	for _, t := range open {
		f := t.Front
		fmt.Fprintf(&b, "| [%s](%s) | %s | `%s` | `%s` | %s | %s |\n", f.ID, t.File, f.Title, f.Status, f.Priority, list(f.Area, "`"), list(f.DependsOn, ""))
	}
	b.WriteString(closedHeader)
	for _, t := range closed {
		fmt.Fprintf(&b, "| [%s](%s) | %s | `%s` | %s |\n", t.Front.ID, t.File, t.Front.Title, t.Front.Status, t.Closed)
	}
	return os.WriteFile(filepath.Join(s.Dir, "INDEX.md"), []byte(b.String()), 0o644)
}

// split returns the open tasks sorted by priority then ID, and the closed tasks sorted by ID.
func split(tasks []Task) (open, closed []Task) {
	for _, t := range tasks {
		if t.Front.Status == "Done" || t.Front.Status == "Cancelled" {
			closed = append(closed, t)
			continue
		}
		open = append(open, t)
	}
	sort.SliceStable(open, func(i, j int) bool {
		if open[i].Front.Priority != open[j].Front.Priority {
			return open[i].Front.Priority < open[j].Front.Priority
		}
		return open[i].Front.ID < open[j].Front.ID
	})
	return open, closed
}

func list(items []string, mark string) string {
	if len(items) == 0 {
		return "None"
	}
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = mark + item + mark
	}
	return strings.Join(quoted, ", ")
}
