package task

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/EqualSoftware/claude-dx/internal/docs/docfile"
)

const indexHeader = `<!-- Generated by claude-dx. Do not edit. -->
# Tasks

This file lists all tasks. Each task is a spec file in this folder: ` + "`TASK-NNN-<short-kebab-title>.md`" + `. Use ` + "`/dx:task`" + ` to make or update a task.

Do not edit this file. The claude-dx task tools make it again from the YAML frontmatter of the task files after each change.

## Priority

| Priority | Meaning |
| :--- | :--- |
| ` + "`P0`" + ` | Blocks other work or breaks the build. Do it first. |
| ` + "`P1`" + ` | Required for the current goal. |
| ` + "`P2`" + ` | Useful. Do it when P0 and P1 tasks are done. |
| ` + "`P3`" + ` | Idea. Do it only if time permits. |

## Status

` + "`Draft` → `In Review` → `Approved` → `In Development` → `Done`" + `. A task can also be ` + "`Blocked` or `Cancelled`" + `.

Open tasks are in one table for each milestone, in version order. Each table is sorted by priority, then by ID. Closed tasks are in the last table.
`

const openHeader = `
## %s

| ID | Title | Status | Priority | Area | Depends on |
| :--- | :--- | :--- | :--- | :--- | :--- |
`

const closedHeader = `
## Closed

` + "`Done` and `Cancelled`" + ` tasks.

| ID | Title | Status | Closed |
| :--- | :--- | :--- | :--- |
`

// WriteIndex makes docs/tasks/README.md from the frontmatter of the task files.
// It is for persons on GitHub; the model uses task_list.
func (s Store) WriteIndex() error {
	tasks, _, err := s.List(Filter{"status": "all"})
	if err != nil {
		return err
	}
	open, closed := split(tasks)
	var b strings.Builder
	b.WriteString(indexHeader)
	for i, t := range open {
		f := t.Front
		if i == 0 || f.Milestone != open[i-1].Front.Milestone {
			fmt.Fprintf(&b, openHeader, milestoneName(f.Milestone))
		}
		fmt.Fprintf(&b, "| [%s](%s) | %s | `%s` | `%s` | %s | %s |\n", f.ID, t.File, docfile.Cell(f.Title), f.Status, f.Priority, list(f.Area, "`"), list(f.DependsOn, ""))
	}
	b.WriteString(closedHeader)
	for _, t := range closed {
		fmt.Fprintf(&b, "| [%s](%s) | %s | `%s` | %s |\n", t.Front.ID, t.File, docfile.Cell(t.Front.Title), t.Front.Status, t.Closed)
	}
	return docfile.Write(filepath.Join(s.Dir, "README.md"), []byte(b.String()))
}

// split returns the open tasks in milestone order, and the closed tasks sorted by ID.
func split(tasks []Task) (open, closed []Task) {
	for _, t := range tasks {
		if t.Front.Status == "Done" || t.Front.Status == "Cancelled" {
			closed = append(closed, t)
			continue
		}
		open = append(open, t)
	}
	sortByMilestone(open)
	return open, closed
}

func milestoneName(m string) string {
	if m == "" {
		return "No milestone"
	}
	return m
}

func list(items []string, mark string) string {
	if len(items) == 0 {
		return "None"
	}
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = mark + item + mark
	}
	return strings.Join(quoted, ", ")
}
