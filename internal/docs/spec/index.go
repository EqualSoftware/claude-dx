package spec

import (
	"fmt"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/EqualSoftware/claude-dx/internal/docs/docfile"
)

const indexHeader = `<!-- Generated by claude-dx. Do not edit. -->
# Specs

This folder has one folder for each spec: ` + "`<slug>/SPEC.md`" + `. A spec is the current definition of one feature. Use ` + "`/dx:spec`" + ` to make or change a spec.

Do not edit this file. The claude-dx spec tools make it again from the YAML frontmatter of the spec files after each change.

| Slug | Title | Status | Milestone | Priority | Area | Requirements |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
`

// WriteIndex makes docs/specs/README.md from the spec files, in milestone order, then by slug.
// It is for persons on GitHub; the model uses spec_list.
func (s Store) WriteIndex() error {
	specs, _, err := s.List(nil)
	if err != nil {
		return err
	}
	sortByMilestone(specs)
	var b strings.Builder
	b.WriteString(indexHeader)
	for _, sp := range specs {
		f := sp.Front
		fmt.Fprintf(&b, "| [%s](%s/%s) | %s | `%s` | %s | `%s` | %s | %d/%d |\n",
			f.Slug, f.Slug, fileName, docfile.Cell(f.Title), f.Status, f.Milestone, f.Priority, areas(f.Area), sp.Done, sp.Total)
	}
	return docfile.Write(filepath.Join(s.Dir, "README.md"), []byte(b.String()))
}

func areas(items []string) string {
	if len(items) == 0 {
		return "None"
	}
	return "`" + strings.Join(items, "`, `") + "`"
}

// sortByMilestone sorts specs by milestone in SemVer order, then by slug.
func sortByMilestone(specs []Spec) {
	slices.SortStableFunc(specs, func(a, b Spec) int {
		if c := slices.Compare(version(a.Front.Milestone), version(b.Front.Milestone)); c != 0 {
			return c
		}
		return strings.Compare(a.Front.Slug, b.Front.Slug)
	})
}

// version returns the numbers of a milestone. A milestone that is not valid comes after all others.
func version(m string) []int {
	parts := milestonePattern.FindStringSubmatch(m)
	if parts == nil {
		return []int{1 << 30}
	}
	v := make([]int, 3)
	for i := range v {
		v[i], _ = strconv.Atoi(parts[i+1]) // The pattern allows only digits.
	}
	return v
}
