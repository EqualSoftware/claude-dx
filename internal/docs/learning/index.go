package learning

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// indexFile is the generated index. It is not a learning.
const indexFile = "README.md"

const indexHeader = `<!-- Generated by claude-dx. Do not edit. -->
# Learnings

This folder has the verified technical lessons of the project. Use ` + "`/dx:learning`" + ` to record a lesson.

| Topic | Description |
| :--- | :--- |
`

// WriteIndex makes docs/learnings/README.md from the frontmatter of the learning files.
// It is for persons on GitHub; the model uses learning_list.
func (s Store) WriteIndex() error {
	list, err := s.List()
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString(indexHeader)
	for _, l := range list {
		fmt.Fprintf(&b, "| [%s](%s.md) | %s |\n", l.Topic, l.Topic, l.Description)
	}
	return os.WriteFile(filepath.Join(s.Dir, indexFile), []byte(b.String()), 0o644)
}
